import '../core/api_client.dart';
import '../core/config.dart';
import '../models/models.dart';

/// Course browsing & detail.
class CourseService {
  final _api = ApiClient.instance;

  Future<List<Course>> browse({String? search, String sort = 'popular', String? category, int limit = 24}) async {
    final data = await _api.get('/courses', query: {
      'limit': limit,
      'sort': sort,
      if (search != null && search.isNotEmpty) 'search': search,
      if (category != null) 'category': category,
    });
    return (data as List).map((c) => Course.fromJson(c as Map<String, dynamic>)).toList();
  }

  Future<Course> bySlug(String slug) async {
    final data = await _api.get('/courses/slug/$slug');
    return Course.fromJson(data as Map<String, dynamic>);
  }

  Future<Course> byId(String id) async {
    final data = await _api.get('/courses/id/$id');
    return Course.fromJson(data as Map<String, dynamic>);
  }

  Future<List<Category>> categories() async {
    final data = await _api.get('/categories');
    return (data as List).map((c) => Category.fromJson(c as Map<String, dynamic>)).toList();
  }

  Future<List<Review>> reviews(String courseId) async {
    final data = await _api.get('/reviews/course/$courseId', query: {'limit': 20});
    return (data as List).map((r) => Review.fromJson(r as Map<String, dynamic>)).toList();
  }

  Future<void> writeReview(String courseId, {required int rating, String? title, String? body}) =>
      _api.post('/reviews/course/$courseId', body: {
        'rating': rating,
        if (title != null && title.isNotEmpty) 'title': title,
        if (body != null && body.isNotEmpty) 'body': body,
      });

  /// Saved AI summary and quiz for a lesson (generated by the instructor).
  Future<LessonExtras> lessonExtras(String lessonId) async {
    final data = await _api.get('/lessons/$lessonId');
    return LessonExtras.fromJson(data as Map<String, dynamic>);
  }
}

/// Enrollments, progress and continue-learning.
class LearningService {
  final _api = ApiClient.instance;

  /// Started-but-unfinished courses, most recently touched first.
  Future<List<Enrollment>> continueLearning() async {
    final data = await _api.get('/enrollments/continue');
    return (data as List).map((e) => Enrollment.fromJson(e as Map<String, dynamic>)).toList();
  }

  Future<List<Enrollment>> myEnrollments() async {
    final data = await _api.get('/enrollments');
    return (data as List).map((e) => Enrollment.fromJson(e as Map<String, dynamic>)).toList();
  }

  Future<EnrollmentStatus> enrollmentStatus(String courseId) async {
    final data = await _api.get('/enrollments/$courseId/status');
    return EnrollmentStatus.fromJson(data as Map<String, dynamic>);
  }

  Future<void> enroll(String courseId) => _api.post('/enrollments/$courseId');

  Future<Map<String, dynamic>> checkoutCourse(String courseId) async {
    final data = await _api.post('/payments/checkout/course/$courseId', body: {
      'client': 'mobile',
    });
    return data as Map<String, dynamic>;
  }

  /// Marks a lesson complete. Returns the certificate code once the course hits 100%.
  Future<String?> completeLesson(String lessonId) async {
    final data = await _api.post('/enrollments/lessons/$lessonId/progress', body: {'completed': true});
    final cert = data is Map ? data['certificate'] : null;
    return cert is Map ? cert['code'] as String? : null;
  }

  Future<List<String>> completedLessonIds(String courseId) async {
    final data = await _api.get('/enrollments/$courseId/progress');
    return (data as List)
        .where((p) => p['isCompleted'] == true)
        .map((p) => p['lessonId'] as String)
        .toList();
  }
}

/// AI tutor.
class AiService {
  final _api = ApiClient.instance;

  Future<String> askTutor(String question, {String? lessonId, List<Map<String, String>>? history}) async {
    final data = await _api.post('/ai/tutor', body: {
      'question': question,
      if (lessonId != null) 'lessonId': lessonId,
      if (history != null) 'history': history,
    });
    return (data as Map<String, dynamic>)['answer'] as String;
  }
}

/// Certificates.
class CertificateService {
  final _api = ApiClient.instance;

  Future<List<Certificate>> mine() async {
    final data = await _api.get('/certificates');
    return (data as List).map((c) => Certificate.fromJson(c as Map<String, dynamic>)).toList();
  }

  static Uri downloadUrl(String code) => Uri.parse('${AppConfig.apiBaseUrl}/certificates/$code/download');
  static Uri verifyUrl(String code) => Uri.parse('${AppConfig.webUrl}/verify/certificate/$code');
}

/// Pro subscription and purchase history.
class BillingService {
  final _api = ApiClient.instance;

  Future<Subscription?> subscription() async {
    final data = await _api.get('/payments/subscription');
    return data is Map<String, dynamic> ? Subscription.fromJson(data) : null;
  }

  Future<void> cancelSubscription() => _api.post('/payments/subscription/cancel');

  Future<List<Purchase>> history() async {
    final data = await _api.get('/payments/history');
    return (data as List).map((p) => Purchase.fromJson(p as Map<String, dynamic>)).toList();
  }

  static Uri pricingUrl() => Uri.parse('${AppConfig.webUrl}/pricing');
}
